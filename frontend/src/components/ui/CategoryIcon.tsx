export function CategoryIcon({ category, size = 'sm' }: { category: string; size?: 'sm' | 'md' }) {
  const definition = getCategoryDefinition(category);
  const Icon = icons[definition.icon as keyof typeof icons] ?? Shapes;
  return (
    <span
      className={`inline-grid shrink-0 place-items-center rounded-full ${size === 'md' ? 'h-8 w-8' : 'h-6 w-6'}`}
      style={{ backgroundColor: definition.tint, color: definition.color }}
    >
      <Icon className={size === 'md' ? 'h-4 w-4' : 'h-3.5 w-3.5'} aria-hidden="true" />
    </span>
  );
}
